// Generates src/api/schema.d.ts from openapi/openapi.json (the Rust server's contract).
// Usage: bun scripts/gen-api.ts            -> rewrites src/api/schema.d.ts
//        bun scripts/gen-api.ts --check    -> exits 1 if schema.d.ts is stale
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { pathToFileURL } from "node:url"

import openapiTS, { astToString } from "openapi-typescript"

const root = resolve(import.meta.dirname, "..")
const input = resolve(root, "openapi/openapi.json")
const output = resolve(root, "src/api/schema.d.ts")

const HEADER =
  "/**\n * Generated by scripts/gen-api.ts from openapi/openapi.json. Do not edit.\n */\n\n"

async function generate(): Promise<string> {
  const ast = await openapiTS(pathToFileURL(input), { alphabetize: true })
  return HEADER + astToString(ast)
}

const next = await generate()
if (process.argv.includes("--check")) {
  const current = existsSync(output) ? readFileSync(output, "utf8") : ""
  if (current !== next) {
    console.error("src/api/schema.d.ts is stale; run `bun run gen:api`.")
    process.exit(1)
  }
  console.log("src/api/schema.d.ts is up to date.")
} else {
  writeFileSync(output, next)
  console.log(`wrote ${output}`)
}
